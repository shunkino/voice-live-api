"""Harvest conversation logs into evaluation datasets.

Parses log files generated by voice-live-scenario.py and extracts
structured turn-level data for Foundry Evaluator input.

Log patterns (from voice-live-scenario.py):
  - User transcript:     "📝 User: {text}"
  - Assistant transcript: "🗣️ Assistant: {text}"
  - classify_and_act:     "classify_and_act: intent={} slots={} summary={}"
  - State transition:     "Transition: {from} -> {to}"
  - Slot update:          "Slot updated: {name} = {value}"
  - Safety trigger:       "Safety rule triggered: type={} action={}"
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys
from dataclasses import dataclass, field

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.dirname(SCRIPT_DIR)
sys.path.insert(0, ROOT_DIR)


@dataclass
class Turn:
    """A single conversation turn extracted from logs."""
    user_transcript: str = ""
    assistant_transcript: str = ""
    intent: str = ""
    slots: dict[str, str] = field(default_factory=dict)
    user_summary: str = ""
    state_before: str = ""
    state_after: str = ""
    safety_triggered: bool = False
    safety_type: str = ""
    safety_action: str = ""


# Regex patterns for log parsing
_RE_USER = re.compile(r"📝 User: (.+)")
_RE_ASSISTANT = re.compile(r"🗣️ Assistant: (.+)")
_RE_CLASSIFY = re.compile(
    r"classify_and_act: intent=(\S+) slots=(\{.*?\}) summary=(.*)"
)
_RE_TRANSITION = re.compile(r"Transition: (\S+) -> (\S+)")
_RE_STATE_LOG = re.compile(r"Turn \d+ \| state=(\S+) \|")
_RE_SLOT_UPDATE = re.compile(r"Slot updated: (\S+) = (.+)")
_RE_SAFETY = re.compile(r"Safety rule triggered: type=(\S+) action=(\S+)")


def parse_log_file(path: str) -> list[Turn]:
    """Parse a scenario log file into a list of Turns."""
    turns: list[Turn] = []
    current_turn: Turn | None = None

    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()

            # User transcript starts a new turn
            m = _RE_USER.search(line)
            if m:
                if current_turn and current_turn.user_transcript:
                    turns.append(current_turn)
                current_turn = Turn(user_transcript=m.group(1))
                continue

            if current_turn is None:
                # Check for state in initial log lines
                m = _RE_STATE_LOG.search(line)
                if m:
                    current_turn = Turn(state_before=m.group(1))
                continue

            # classify_and_act args
            m = _RE_CLASSIFY.search(line)
            if m:
                current_turn.intent = m.group(1)
                try:
                    current_turn.slots = eval(m.group(2))  # noqa: S307
                except Exception:
                    current_turn.slots = {}
                current_turn.user_summary = m.group(3)
                continue

            # State before (from Turn log)
            m = _RE_STATE_LOG.search(line)
            if m:
                current_turn.state_before = m.group(1)
                continue

            # State transition
            m = _RE_TRANSITION.search(line)
            if m:
                if not current_turn.state_before:
                    current_turn.state_before = m.group(1)
                current_turn.state_after = m.group(2)
                continue

            # Slot update
            m = _RE_SLOT_UPDATE.search(line)
            if m:
                current_turn.slots[m.group(1)] = m.group(2)
                continue

            # Safety
            m = _RE_SAFETY.search(line)
            if m:
                current_turn.safety_triggered = True
                current_turn.safety_type = m.group(1)
                current_turn.safety_action = m.group(2)
                continue

            # Assistant transcript
            m = _RE_ASSISTANT.search(line)
            if m:
                current_turn.assistant_transcript = m.group(1)
                continue

    # Don't forget the last turn
    if current_turn and current_turn.user_transcript:
        turns.append(current_turn)

    return turns


def turns_to_eval_rows(turns: list[Turn]) -> list[dict]:
    """Convert parsed turns into Foundry evaluation dataset rows."""
    rows: list[dict] = []
    for turn in turns:
        if not turn.user_transcript:
            continue

        state_after = turn.state_after or turn.state_before or "unknown"

        # Build expected_behavior from what actually happened
        expected_parts = []
        if turn.intent:
            expected_parts.append(f"Intent '{turn.intent}' を認識")
        if turn.state_before and turn.state_after:
            expected_parts.append(
                f"状態 '{turn.state_before}' → '{turn.state_after}' へ遷移"
            )
        if turn.safety_triggered:
            expected_parts.append(
                f"安全ルール {turn.safety_type}/{turn.safety_action} が発動"
            )
        if turn.slots:
            expected_parts.append(f"スロット収集: {turn.slots}")

        row: dict = {
            "query": turn.user_transcript,
            "context": (
                f"state_before={turn.state_before or 'unknown'}, "
                f"intent={turn.intent}, slots={turn.slots}"
            ),
            "expected_behavior": "。".join(expected_parts) if expected_parts else "適切に応答する",
        }

        if turn.assistant_transcript:
            row["response"] = turn.assistant_transcript

        rows.append(row)

    return rows


def harvest_logs(
    log_dir: str,
    pattern: str = "*_scenario.log",
) -> list[dict]:
    """Harvest all matching log files into evaluation rows."""
    log_files = sorted(glob.glob(os.path.join(log_dir, pattern)))
    all_rows: list[dict] = []

    for log_file in log_files:
        turns = parse_log_file(log_file)
        rows = turns_to_eval_rows(turns)
        all_rows.extend(rows)
        print(f"  {os.path.basename(log_file)}: {len(turns)} turns -> {len(rows)} eval rows")

    return all_rows


def write_jsonl(rows: list[dict], output_path: str) -> None:
    """Write rows to JSONL file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main():
    parser = argparse.ArgumentParser(
        description="Harvest conversation logs into evaluation datasets"
    )
    parser.add_argument(
        "--log-dir",
        default=os.path.join(ROOT_DIR, "logs"),
        help="Directory containing scenario log files",
    )
    parser.add_argument(
        "--pattern",
        default="*_scenario.log",
        help="Glob pattern for log files",
    )
    parser.add_argument(
        "--output", "-o",
        default=None,
        help="Output JSONL path",
    )
    args = parser.parse_args()

    if not os.path.isdir(args.log_dir):
        print(f"Log directory not found: {args.log_dir}")
        sys.exit(1)

    rows = harvest_logs(args.log_dir, args.pattern)

    if not rows:
        print("No turns found in log files.")
        sys.exit(0)

    if args.output:
        output_path = args.output
    else:
        output_path = os.path.join(
            ROOT_DIR, ".foundry", "datasets",
            "interview_practice-eval-logs-v1.jsonl",
        )

    write_jsonl(rows, output_path)
    print(f"Harvested {len(rows)} evaluation rows -> {output_path}")


if __name__ == "__main__":
    main()
